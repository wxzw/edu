INSERT INTO sys_role_permission (role_id, permission_id, created_by, updated_by)
SELECT r.id, p.id, 1, 1
FROM sys_role r
JOIN sys_permission p ON p.code = 'operation:admission' AND p.deleted = 0
WHERE r.code IN ('SUPER_ADMIN', 'CAMPUS_ADMIN')
  AND r.deleted = 0
  AND NOT EXISTS (
      SELECT 1
      FROM sys_role_permission existing
      WHERE existing.role_id = r.id
        AND existing.permission_id = p.id
        AND existing.deleted = 0
  );

DO $$
DECLARE
  table_name TEXT;
BEGIN
  FOREACH table_name IN ARRAY ARRAY[
    'edu_course_teacher',
    'edu_course_registration'
  ]
  LOOP
    EXECUTE FORMAT('DROP TRIGGER IF EXISTS trg_set_updated_at ON %I', table_name);
    EXECUTE FORMAT(
      'CREATE TRIGGER trg_set_updated_at BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at()',
      table_name
    );
  END LOOP;
END;
$$;
