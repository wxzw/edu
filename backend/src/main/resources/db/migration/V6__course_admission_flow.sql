  ADD COLUMN IF NOT EXISTS avatar_url VARCHAR(512);

CREATE TABLE IF NOT EXISTS edu_course_teacher (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campus_id BIGINT NOT NULL REFERENCES sys_campus (id),
  course_id BIGINT NOT NULL,
  teacher_id BIGINT NOT NULL,
  role_name VARCHAR(50),
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  created_by BIGINT,
  updated_by BIGINT,
  deleted SMALLINT NOT NULL DEFAULT 0,
  version INTEGER NOT NULL DEFAULT 0,
  CONSTRAINT uk_edu_course_teacher_campus_id_id UNIQUE (campus_id, id),
  CONSTRAINT fk_course_teacher_course FOREIGN KEY (campus_id, course_id) REFERENCES edu_course (campus_id, id),
  CONSTRAINT fk_course_teacher_teacher FOREIGN KEY (campus_id, teacher_id) REFERENCES edu_teacher (campus_id, id)
);
COMMENT ON TABLE edu_course_teacher IS 'Public course teacher display relation';
CREATE UNIQUE INDEX IF NOT EXISTS uk_course_teacher_alive
  ON edu_course_teacher (campus_id, course_id, teacher_id) WHERE deleted = 0;

CREATE TABLE IF NOT EXISTS edu_course_registration (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campus_id BIGINT NOT NULL REFERENCES sys_campus (id),
  course_id BIGINT NOT NULL,
  student_id BIGINT,
  guardian_id BIGINT NOT NULL,
  order_id BIGINT,
  preferred_class_id BIGINT,
  assigned_class_id BIGINT,
  registration_no VARCHAR(40) NOT NULL,
  applicant_name VARCHAR(50),
  applicant_phone VARCHAR(20) NOT NULL,
  child_name VARCHAR(50) NOT NULL,
  child_age NUMERIC(4, 1),
  child_grade VARCHAR(30),
  amount NUMERIC(10, 2) NOT NULL DEFAULT 0,
  status VARCHAR(30) NOT NULL DEFAULT 'WAITING_PAY',
  note VARCHAR(500),
  review_remark VARCHAR(500),
  registered_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  paid_at TIMESTAMPTZ,
  reviewed_at TIMESTAMPTZ,
  confirmed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  created_by BIGINT,
  updated_by BIGINT,
  deleted SMALLINT NOT NULL DEFAULT 0,
  version INTEGER NOT NULL DEFAULT 0,
  CONSTRAINT uk_course_registration_campus_id_id UNIQUE (campus_id, id),
  CONSTRAINT fk_course_registration_course FOREIGN KEY (campus_id, course_id) REFERENCES edu_course (campus_id, id),
  CONSTRAINT fk_course_registration_student FOREIGN KEY (campus_id, student_id) REFERENCES edu_student (campus_id, id),
  CONSTRAINT fk_course_registration_guardian FOREIGN KEY (campus_id, guardian_id) REFERENCES edu_guardian (campus_id, id),
  CONSTRAINT fk_course_registration_order FOREIGN KEY (campus_id, order_id) REFERENCES fin_order (campus_id, id),
  CONSTRAINT fk_course_registration_preferred_class FOREIGN KEY (campus_id, preferred_class_id) REFERENCES edu_class (campus_id, id),
  CONSTRAINT fk_course_registration_assigned_class FOREIGN KEY (campus_id, assigned_class_id) REFERENCES edu_class (campus_id, id)
);
COMMENT ON TABLE edu_course_registration IS 'Course registration and admission workflow';
CREATE UNIQUE INDEX IF NOT EXISTS uk_course_registration_no_alive
  ON edu_course_registration (registration_no) WHERE deleted = 0;
CREATE INDEX IF NOT EXISTS idx_course_registration_status
  ON edu_course_registration (campus_id, status, registered_at DESC);
CREATE INDEX IF NOT EXISTS idx_course_registration_guardian
  ON edu_course_registration (campus_id, guardian_id, registered_at DESC);

